#!/usr/bin/env bash
# Builds VSCodeSwitcher.app out of the SwiftPM release binary.
#
#   macos/scripts/build.sh              build the binary and assemble the bundle
#   macos/scripts/build.sh --skip-build reuse the binary already in .build
#
# The bundle also carries the hooks and the hook installer, so "Install hooks"
# in the menu works for an app copied to /Applications.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
MACOS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_DIR="$(cd "$MACOS_DIR/.." && pwd)"
APP_NAME="VSCodeSwitcher"
BUILD_DIR="$MACOS_DIR/.build"
APP_BUNDLE="$MACOS_DIR/$APP_NAME.app"
APP_ICON_SOURCE="$MACOS_DIR/Resources/AppIcon.icns"
MENUBAR_ICON_SOURCES=(
    "$MACOS_DIR/Resources/MenuBarIconTemplate.png"
    "$MACOS_DIR/Resources/MenuBarIconTemplate@2x.png"
)
PLIST_BUDDY="/usr/libexec/PlistBuddy"
SKIP_BUILD=0

while [[ $# -gt 0 ]]; do
    case "$1" in
        --skip-build) SKIP_BUILD=1 ;;
        *) echo "Error: unknown option '$1'" >&2; exit 1 ;;
    esac
    shift
done

cd "$MACOS_DIR"

if [[ "$SKIP_BUILD" -eq 0 ]]; then
    echo "==> Building release binary..."
    swift build -c release
fi

BINARY="$BUILD_DIR/release/$APP_NAME"
if [[ ! -f "$BINARY" ]]; then
    echo "Error: binary not found at $BINARY" >&2
    exit 1
fi

echo "==> Assembling $APP_NAME.app..."
# Replacing the bundle under a running copy leaves that process alive with a
# deleted executable: the menu bar icon stays, the Accessibility entry no longer
# matches anything, and the failures that follow look like app bugs. Only the
# instance launched from *this* bundle is stopped — a copy in /Applications is
# somebody else's business.
if pgrep -f "^$APP_BUNDLE/Contents/MacOS/$APP_NAME$" >/dev/null 2>&1; then
    echo "    stopping the running instance of this bundle"
    pkill -f "^$APP_BUNDLE/Contents/MacOS/$APP_NAME$" || true
    sleep 0.5
fi

rm -rf "$APP_BUNDLE"
mkdir -p "$APP_BUNDLE/Contents/MacOS"
mkdir -p "$APP_BUNDLE/Contents/Resources"

cp "$MACOS_DIR/Resources/Info.plist" "$APP_BUNDLE/Contents/Info.plist"
cp "$BINARY" "$APP_BUNDLE/Contents/MacOS/$APP_NAME"

APP_VERSION="${APP_VERSION:-$("$PLIST_BUDDY" -c 'Print :CFBundleShortVersionString' "$APP_BUNDLE/Contents/Info.plist")}"
APP_BUILD="${APP_BUILD:-$(git -C "$REPO_DIR" rev-list --count HEAD 2>/dev/null || echo 1)}"
"$PLIST_BUDDY" -c "Set :CFBundleShortVersionString $APP_VERSION" "$APP_BUNDLE/Contents/Info.plist"
"$PLIST_BUDDY" -c "Set :CFBundleVersion $APP_BUILD" "$APP_BUNDLE/Contents/Info.plist"

echo "==> Bundling icons..."
# CFBundleIconFile points at AppIcon; the status item loads
# MenuBarIconTemplate by name. Both are generated by make-icons.sh and
# committed, so a missing one means the working copy is broken, not that the
# icons were never made.
for icon in "$APP_ICON_SOURCE" "${MENUBAR_ICON_SOURCES[@]}"; do
    if [[ ! -f "$icon" ]]; then
        echo "Error: icon not found at $icon — run 'make icons'" >&2
        exit 1
    fi
    cp "$icon" "$APP_BUNDLE/Contents/Resources/"
done

echo "==> Bundling hooks and the installer..."
mkdir -p "$APP_BUNDLE/Contents/Resources/hooks" "$APP_BUNDLE/Contents/Resources/scripts"
cp "$REPO_DIR"/hooks/*.sh "$APP_BUNDLE/Contents/Resources/hooks/"
cp "$REPO_DIR/scripts/install-hooks.sh" "$APP_BUNDLE/Contents/Resources/scripts/"
chmod +x "$APP_BUNDLE/Contents/Resources/hooks/"*.sh "$APP_BUNDLE/Contents/Resources/scripts/install-hooks.sh"

# ditto and friends can leave Finder metadata behind, which makes codesign fail
# with "resource fork, Finder information, or similar detritus not allowed".
xattr -cr "$APP_BUNDLE"

# An ad-hoc signature carries no certificate, so TCC has nothing stable to key
# the Accessibility grant on and falls back to the code directory hash — which
# changes with every single rebuild. That, and nothing else, is why the
# permission has to be re-granted after each `make app`. A self-signed
# certificate gives the bundle a designated requirement that survives rebuilds,
# and the grant survives with it. Creating that certificate is left to the
# user; the README describes both ways, through Keychain Access and from the
# terminal. This picks the certificate up automatically once it exists.
SIGN_IDENTITY="${SIGN_IDENTITY:-VSCodeSwitcher Dev}"
if security find-identity -v -p codesigning 2>/dev/null | grep -qF "\"$SIGN_IDENTITY\""; then
    echo "==> Codesigning with '$SIGN_IDENTITY'..."
    codesign --force --sign "$SIGN_IDENTITY" "$APP_BUNDLE"
else
    echo "==> Codesigning (ad-hoc — the Accessibility grant will not survive rebuilds;"
    echo "    create a '$SIGN_IDENTITY' code signing certificate to fix that, see README)"
    codesign --force --sign - "$APP_BUNDLE"
fi
codesign -v "$APP_BUNDLE"

echo "==> Built $APP_BUNDLE"

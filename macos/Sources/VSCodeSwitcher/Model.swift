import CoreGraphics
import Foundation

/// What a Claude session is doing right now.
///
/// The order of the cases is the aggregation priority: when a window hosts
/// several sessions, the window shows the highest one.
enum AgentState: String, Codable, Sendable, CaseIterable, Comparable {
    /// Alive but nothing happened for a while.
    case idle
    /// Claude is executing a turn.
    case working
    /// Claude answered and waits for the user.
    case waiting
    /// Claude is blocked on a permission or elicitation dialog.
    case permission
    /// Claude asked the user something — `AskUserQuestion`, or a plan waiting
    /// for approval — and cannot go on until it is answered.
    case question

    var priority: Int {
        switch self {
        case .idle: return 0
        case .working: return 1
        case .waiting: return 2
        case .permission: return 3
        case .question: return 4
        }
    }

    static func < (lhs: AgentState, rhs: AgentState) -> Bool {
        lhs.priority < rhs.priority
    }
}

/// What a row's single indicator says, folded from every chat and background
/// subagent it holds.
///
/// The row answers a question about the *window*, not about its chats: am I
/// standing in its way, has it left something for me to read, is anything
/// moving, or is it all asleep. The per-chat breakdown lives in the tooltip.
///
/// Listed least urgent first. Nothing derives an order from the case list — the
/// fold's priority is written out, step by step, in `SwitcherRow.status` — but
/// the two are kept in the same order so reading one does not mislead about the
/// other. That order is *not* `AgentState`'s: there `waiting` outranks
/// `working`, here `active` outranks `done`.
///
/// Not `Codable`: the fold is derived from `sessions`, never stored and never
/// decoded, and a conformance nothing uses is a conformance that can rot.
enum RowStatus: String, Sendable, CaseIterable {
    /// Nothing running and nothing to answer.
    case asleep
    /// A chat finished its turn and nobody has read it. Nothing is blocked; the
    /// user reads it whenever it suits them.
    case done
    /// A chat is taking a turn, or a background subagent is running under one.
    case active
    /// A chat stopped *mid-task* and cannot go on until the user presses
    /// something: a question, or a permission dialog. The bottleneck is the
    /// human, and every second of it is idle time.
    case blocked
}

/// Where a session's state came from. Useful for diagnostics: the hook value is
/// authoritative, the transcript value lags by tens of seconds.
enum AgentStateSource: String, Codable, Sendable {
    case hook
    case transcript
    case unknown
}

/// A background subagent spawned by a session.
struct SubagentInfo: Sendable, Codable, Identifiable {
    var id: String
    var agentType: String?
    var description: String?
    var lastActivity: Date?
    var isActive: Bool
}

/// One live Claude Code session, enriched with whatever the state files and the
/// transcript tail could tell us.
struct ClaudeSessionInfo: Sendable, Codable, Identifiable {
    var id: String { sessionId }

    var sessionId: String
    var pid: Int32
    var cwd: String
    /// Session name from the session file (`name`), e.g. `home-network-ea`.
    var name: String?
    /// Chat topic generated by Claude; the full version of the window title prefix.
    var aiTitle: String?
    /// Last user prompt, used as a topic fallback before `ai-title` exists.
    var lastPrompt: String?
    var state: AgentState
    var stateSource: AgentStateSource
    var model: String?
    var contextUsedTokens: Int?
    var contextLimitTokens: Int?
    var activeSubagents: Int
    var subagents: [SubagentInfo]
    var lastActivity: Date?

    /// Best available label for the chat.
    var topic: String? {
        if let aiTitle, !aiTitle.isEmpty { return aiTitle }
        if let lastPrompt, !lastPrompt.isEmpty { return lastPrompt }
        return nil
    }

    var contextFraction: Double? {
        guard let used = contextUsedTokens, let limit = contextLimitTokens, limit > 0 else { return nil }
        return Double(used) / Double(limit)
    }
}

/// A project directory found under one of the configured scan roots.
struct ProjectInfo: Sendable, Codable, Identifiable, Hashable {
    var id: String { path }

    /// Absolute path of the project directory.
    var path: String
    /// Name shown in the list: the directory name, prefixed with the parent
    /// directory when the project sits below a root's first level.
    var displayName: String
    /// Name VSCode puts in the window title: the `.code-workspace` file name
    /// without extension, otherwise the directory name.
    var rootName: String
    /// `#rrggbb`, resolved from Peacock/colorCustomizations or hashed from the name.
    var colorHex: String
    /// Absolute path of the `.code-workspace` file, when the project has one.
    var workspaceFile: String?
    /// Directory modification time, used to order the "not open" section.
    var mtime: Date
}

/// How much Claude Code work a project has seen, which is what orders the
/// projects that have no window of their own.
struct ProjectActivity: Sendable, Equatable {
    /// Sessions whose transcript was last written inside the activity window.
    var recentSessions: Int = 0
    /// When the newest session of this project was last written, of any age.
    /// Breaks ties, and orders the projects with nothing inside the window.
    var lastSession: Date?
}

/// A VSCode window as reported by the Accessibility API.
///
/// Deliberately free of `AXUIElement` so the model stays `Sendable`: the element
/// is resolved again from `pid` + `windowNumber` when a window has to be raised.
struct VSCodeWindowInfo: Sendable, Codable, Identifiable, Hashable {
    /// Stable for as long as the window exists, and — unlike the z-order index
    /// it falls back to — unaffected by raising any window. Every row's
    /// identity used to change on every click, which reset the selection, the
    /// hover highlight and the scroll position of the whole list.
    var id: String {
        guard let windowNumber else { return "\(pid):\(windowIndex)" }
        return "\(pid):w\(windowNumber)"
    }

    var pid: Int32
    /// Position in the AX window array, which is the z-order (0 = frontmost).
    /// Changes whenever any window is raised; only good for MRU ordering.
    var windowIndex: Int
    /// `CGWindowID` of the window, from the private `_AXUIElementGetWindow`.
    /// `nil` only when that call is unavailable.
    var windowNumber: CGWindowID?
    var title: String
    /// Tail of the title after the last separator, without ` (Workspace)`.
    var rootName: String?
    /// Head of the title before the last separator: the active chat topic,
    /// truncated with an ellipsis by VSCode itself.
    var chatTopicPrefix: String?
    /// True when the title carried the ` (Workspace)` suffix.
    var isWorkspace: Bool
    var isMinimized: Bool
}

enum SwitcherRowKind: String, Sendable, Codable {
    /// An open VSCode window.
    case window
    /// A project from the index that has no window open.
    case project
}

/// One row of the switcher list: either an open window or a project that can be
/// opened. Everything the UI needs is precomputed here.
struct SwitcherRow: Sendable, Codable, Identifiable {
    var id: String
    var kind: SwitcherRowKind

    var displayName: String
    var colorHex: String
    var project: ProjectInfo?
    var window: VSCodeWindowInfo?

    /// Sessions attributed to this row, most recently active first.
    var sessions: [ClaudeSessionInfo]
    /// Highest state among `sessions`; `nil` when the row has none.
    var state: AgentState?
    /// Total active background subagents across `sessions`.
    var activeSubagents: Int
    var subagentDescriptions: [String]

    /// Metrics of the session considered active for this row.
    var chatTopic: String?
    var model: String?
    var contextUsedTokens: Int?
    var contextLimitTokens: Int?
    var lastActivity: Date?

    var contextFraction: Double? {
        guard let used = contextUsedTokens, let limit = contextLimitTokens, limit > 0 else { return nil }
        return Double(used) / Double(limit)
    }

    /// The one indicator the row draws, or `nil` when the row has nothing to
    /// say and the slot stays empty.
    ///
    /// The priority is `blocked` > `active` > `done` > `asleep`, and it is spelled
    /// out here rather than taken from `state`: it deliberately differs from
    /// `AgentState`'s own order, where `waiting` outranks `working`.
    ///
    /// "Done" is a claim about the *past* — a turn that finished. "Active" is a
    /// claim about the *present*. While anything in the window is still running
    /// the window is not finished, and the honest answer is "busy, come back
    /// later", not "ready, go read it". The green tick has to mean the window
    /// really has gone quiet and only the reading is left. This was caught live:
    /// the main chat had answered while a subagent went on working, and the row
    /// declared itself done over a window that was visibly working.
    ///
    /// `blocked` still outranks everything: that chat needs a human and the wait
    /// is pure idle time, which does not keep. `done` is a message that does.
    ///
    /// Subagents are the second half of "something is moving": they go on
    /// running under a chat that has already answered, and under one sitting in
    /// `idle`.
    ///
    /// `nil` is not a fifth answer, it is the absence of a subject: a project
    /// with no agent in it is not "asleep", there is simply nothing there to be
    /// asleep. The distinction earns its keep in the "projects" section, which
    /// is ninety-odd rows most of which have never seen an agent — an icon
    /// identical on all of them would distinguish nothing and be pure noise
    /// along the longest stretch of the list. `asleep` stays for the rows where
    /// it is a real outcome of four: a window whose chats are alive but idle,
    /// or a project running an agent without a window.
    ///
    /// Sessions are the only source of subagents (`DataSource.aggregate` sums
    /// them over `sessions`), so "no session" already implies "no subagent" and
    /// the emptiness of `sessions` is the whole test.
    ///
    /// The user asked for the indicator to have a fixed *place*, not to be
    /// present on every row, and an empty slot of fixed width answers that in
    /// full: whenever there is an icon, it is at the same x.
    var status: RowStatus? {
        guard !sessions.isEmpty else { return nil }
        if sessions.contains(where: { $0.state == .question || $0.state == .permission }) { return .blocked }
        if sessions.contains(where: { $0.state == .working }) || activeSubagents > 0 { return .active }
        if sessions.contains(where: { $0.state == .waiting }) { return .done }
        return .asleep
    }

    /// The one number the row shows, in the title line after the name
    /// (`vscode-switcher (agents: 5)`): chats taking a turn plus the background
    /// subagents running under them.
    ///
    /// Orthogonal to `status` on purpose — a row can want an answer from the
    /// user *and* have subagents grinding away, and both facts are worth
    /// seeing at once.
    var activeCount: Int {
        sessions.filter { $0.state == .working }.count + activeSubagents
    }
}

/// Everything the panel renders, as one immutable value.
struct SwitcherSnapshot: Sendable, Codable {
    var openWindows: [SwitcherRow]
    var projects: [SwitcherRow]
    var accessibilityTrusted: Bool
    /// When the sources were read, not when the assembly finished — the two are
    /// 40–180 ms apart and this is the age of the data.
    var generatedAt: Date

    var rows: [SwitcherRow] { openWindows + projects }
}
